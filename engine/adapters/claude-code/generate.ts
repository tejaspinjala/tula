#!/usr/bin/env bun
// Claude Code adapter: emits `.claude/agents/*.md` for WHATEVER org exists in a $FLEET_HOME (or any directory with
// the same layout). Nothing here names a department, role or agent: it reads the `agent`, `role`, `department`
// and `providers` config kinds through the P0-6 registry.
//   bun engine/adapters/claude-code/generate.ts [--home DIR] [--out PROJECT_DIR] [--check] [--provider ID] [--common FILE]
// Defaults: home = $FLEET_HOME (or ~/.tula-fleet), out = $CLAUDE_PROJECT_DIR or cwd.
import fs from 'node:fs';
import path from 'node:path';
import { fleetHome } from '../../lib/paths.ts';
import { createDefaultRegistry } from '../../home/registry.ts';
import type { Org, OrgNode, TierModels } from '../../lib/types.ts';
import type { Agent } from '../../schema/agent.ts';
import type { Department } from '../../schema/department.ts';
import type { Providers } from '../../schema/providers.ts';
import type { Role } from '../../schema/role.ts';

export const GENERATED_MARKER = '<!-- generated by engine/adapters/claude-code/generate.ts from the org data; edit the data, not this file -->';
export const DEFAULT_COMMON = path.resolve(import.meta.dir, '..', '..', 'prompts', 'common.md');

export interface LoadedOrg {
  org: Org;
  models: TierModels;
  /** provider id the tier -> model map came from, if any */
  provider?: string;
}

/** Reads agents + roles + departments + providers from `dir` and joins them into the flat node list adapters use. */
export async function loadOrg(dir: string, opts: { provider?: string } = {}): Promise<LoadedOrg> {
  const reg = createDefaultRegistry(dir);
  const res = await reg.loadAll();
  const bad = res.issues.filter((i) => ['agent', 'role', 'department', 'providers', 'company'].includes(i.kind));
  if (bad.length) throw new Error(`org in ${dir} has invalid config:\n  - ${bad.map((b) => `${b.kind}/${b.id}: ${b.message}`).join('\n  - ')}`);
  const roles = reg.all<Role>('role');
  const depts = reg.all<Department>('department');
  const agents = Object.values(reg.all<Agent>('agent')).sort((a, b) => a.id.localeCompare(b.id));
  const nodes: OrgNode[] = [];
  const errs: string[] = [];
  for (const a of agents) {
    if (a.status !== 'active') continue;
    const r = roles[a.roleId];
    if (!r) { errs.push(`agent '${a.id}': role '${a.roleId}' does not exist`); continue; }
    nodes.push({
      id: a.id,
      name: a.displayName,
      title: r.title,
      level: r.level,
      tier: r.tier,
      parent: a.parentAgentId,
      room: depts[a.departmentId]?.room,
      desc: r.description ?? r.title,
      tools: r.nativeTools,
      role: r.dutiesPrompt,
      ...(r.maxTurns ? { maxTurns: r.maxTurns } : {}),
    });
  }
  if (errs.length) throw new Error(errs.join('\n'));
  const ids = new Set(nodes.map((n) => n.id));
  for (const n of nodes) if (n.parent && !ids.has(n.parent)) n.parent = null; // parent inactive: the child becomes a root

  const provs = (reg.get<Providers>('providers')?.providers ?? {}) as Providers['providers'];
  const wanted = opts.provider ?? process.env.FLEET_PROVIDER;
  let provider: string | undefined;
  if (wanted) {
    if (!provs[wanted]) throw new Error(`unknown provider "${wanted}"`);
    provider = wanted;
  } else {
    provider = Object.keys(provs).sort().find((k) => provs[k]!.adapter === 'claude-code' && !provs[k]!.disabled);
  }
  const models: TierModels = provider ? { ...provs[provider]!.tiers } : {};
  return { org: { company: reg.get<{ name: string }>('company')?.name ?? '', nodes }, models, provider };
}

export function renderAgent(node: OrgNode, org: Org, models: TierModels, common: string): string {
  const children = org.nodes.filter((n) => n.parent === node.id).map((n) => n.id);
  const tools = node.tools.map((t) => (t === 'Agent' ? (children.length ? `Agent(${children.join(', ')})` : null) : t)).filter((t): t is string => t !== null);
  const model = models[node.tier] || 'inherit';
  const fm = [
    '---',
    `name: ${node.id}`,
    `description: ${JSON.stringify(node.desc)}`,
    `model: ${model}`,
    `tools: ${tools.join(', ')}`,
    ...(node.maxTurns ? [`maxTurns: ${node.maxTurns}`] : []),
    '---',
  ].join('\n');
  const body = `# ${node.name} - ${node.title}\n${node.role}\n\n${common}`;
  return `${fm}\n${GENERATED_MARKER}\n${body}\n`;
}

/** One file per active agent; `file` is relative to the project dir. */
export function renderAll(org: Org, models: TierModels, common: string): { file: string; text: string }[] {
  return org.nodes.map((n) => ({ file: path.join('.claude', 'agents', `${n.id}.md`), text: renderAgent(n, org, models, common) }));
}

export interface SyncResult {
  total: number;
  changed: string[];
  removed: string[];
}

/** Writes (or with `check`, only compares) the agent files under `outDir`. Removes stale generated files. */
export async function syncAgents(opts: { home: string; outDir: string; common?: string; check?: boolean; provider?: string }): Promise<SyncResult> {
  const { org, models } = await loadOrg(opts.home, { provider: opts.provider });
  const common = fs.readFileSync(opts.common ?? DEFAULT_COMMON, 'utf8').trim();
  const out = renderAll(org, models, common);
  const changed: string[] = [];
  const agentsDir = path.join(opts.outDir, '.claude', 'agents');
  if (!opts.check) fs.mkdirSync(agentsDir, { recursive: true });
  for (const { file, text } of out) {
    const abs = path.join(opts.outDir, file);
    const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (cur !== text) {
      changed.push(file);
      if (!opts.check) fs.writeFileSync(abs, text);
    }
  }
  const keep = new Set(out.map((o) => path.basename(o.file)));
  const removed: string[] = [];
  if (fs.existsSync(agentsDir)) {
    for (const f of fs.readdirSync(agentsDir)) {
      if (!f.endsWith('.md') || keep.has(f)) continue;
      const abs = path.join(agentsDir, f);
      if (!fs.readFileSync(abs, 'utf8').includes(GENERATED_MARKER)) continue; // never touch hand-written agents
      removed.push(path.join('.claude', 'agents', f));
      if (!opts.check) fs.rmSync(abs);
    }
  }
  return { total: out.length, changed, removed };
}

export async function main(argv: string[], io: { out: (s: string) => void; err: (s: string) => void } = { out: console.log, err: console.error }): Promise<number> {
  const get = (k: string): string | undefined => { const i = argv.indexOf('--' + k); return i >= 0 ? argv[i + 1] : undefined; };
  const known = new Set(['--home', '--out', '--check', '--provider', '--common']);
  const unknown = argv.filter((a, i) => a.startsWith('--') && !known.has(a) && !(i > 0 && argv[i - 1] === a));
  if (unknown.length) { io.err(`unknown argument ${unknown[0]}\nusage: generate.ts [--home DIR] [--out DIR] [--check] [--provider ID] [--common FILE]`); return 2; }
  const check = argv.includes('--check');
  try {
    const r = await syncAgents({
      home: path.resolve(get('home') ?? fleetHome()),
      outDir: path.resolve(get('out') ?? process.env.CLAUDE_PROJECT_DIR ?? process.cwd()),
      common: get('common'),
      provider: get('provider'),
      check,
    });
    const stale = r.changed.length + r.removed.length;
    if (check && stale) { io.err(`${stale} agent file(s) out of date. Run: bun run sync`); return 1; }
    io.out(check ? 'agents up to date' : `synced ${r.total} agents (${r.changed.length} changed, ${r.removed.length} removed)`);
    return 0;
  } catch (e) {
    io.err((e as Error).message);
    return 1;
  }
}

if (import.meta.main) process.exit(await main(process.argv.slice(2)));
