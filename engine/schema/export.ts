// Generates engine/schema/index.ts and engine/schema/json/<entity>.schema.json (JSON Schema 2020-12) from the
// Zod schemas in engine/schema/*.ts.
//
//   bun run schema:export           write index.ts + json/*.schema.json (and delete stale json files)
//   bun run schema:export --check   regenerate in memory; exit 1 with a diff summary if anything differs
//
// Module convention (one file per entity, kebab-case name `<name>.ts`):
//   - an entity module exports `<camelName>Schema` (a Zod schema) and goes into the `schemas` registry;
//   - a library module (common.ts) exports `<camelName>Defs` (a record of Zod schemas) and is emitted as a
//     JSON Schema file holding only `$defs`.
import fs from 'node:fs';
import path from 'node:path';
import { z } from 'zod';

export const SCHEMA_DIR = import.meta.dir;
export const JSON_DIR = path.join(SCHEMA_DIR, 'json');
const NOT_SCHEMA_MODULES = new Set(['index', 'export']);
const JSON_SCHEMA_DIALECT = 'https://json-schema.org/draft/2020-12/schema';

export interface SchemaModule {
  name: string;
  entity?: z.ZodType;
  defs?: Record<string, z.ZodType>;
}

export function camel(name: string): string {
  return name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
}

export function moduleNames(dir: string = SCHEMA_DIR): string[] {
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts'))
    .map((f) => f.slice(0, -3))
    .filter((n) => !NOT_SCHEMA_MODULES.has(n))
    .sort();
}

export async function loadModules(dir: string = SCHEMA_DIR): Promise<SchemaModule[]> {
  const out: SchemaModule[] = [];
  for (const name of moduleNames(dir)) {
    if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`schema module name must be kebab-case: ${name}.ts`);
    const mod = (await import(path.join(dir, `${name}.ts`))) as Record<string, unknown>;
    const entity = mod[`${camel(name)}Schema`];
    const defs = mod[`${camel(name)}Defs`];
    if (entity instanceof z.ZodType) out.push({ name, entity });
    else if (defs && typeof defs === 'object') out.push({ name, defs: defs as Record<string, z.ZodType> });
    else throw new Error(`${name}.ts exports neither ${camel(name)}Schema nor ${camel(name)}Defs`);
  }
  return out;
}

type Json = Record<string, unknown>;

function toJson(schema: z.ZodType): Json {
  return z.toJSONSchema(schema, { target: 'draft-2020-12', io: 'input', unrepresentable: 'throw' }) as Json;
}

export function jsonSchemaFor(m: SchemaModule): Json {
  if (m.entity) {
    const { $schema: _dialect, ...rest } = toJson(m.entity);
    return { $schema: JSON_SCHEMA_DIALECT, $id: m.name, ...rest };
  }
  const defs: Record<string, unknown> = {};
  for (const [key, schema] of Object.entries(m.defs ?? {})) {
    const js = toJson(schema);
    const ref = typeof js.$ref === 'string' ? js.$ref : undefined;
    if (ref !== `#/$defs/${key}`) throw new Error(`${m.name}Defs.${key} must carry .meta({ id: '${key}' })`);
    for (const [k, v] of Object.entries((js.$defs ?? {}) as Record<string, unknown>)) {
      if (k in defs && JSON.stringify(defs[k]) !== JSON.stringify(v)) throw new Error(`conflicting $defs/${k} in ${m.name}`);
      defs[k] = v;
    }
  }
  return { $schema: JSON_SCHEMA_DIALECT, $id: m.name, $defs: defs };
}

export function renderJson(value: unknown): string {
  return JSON.stringify(value, null, 2) + '\n';
}

export function renderIndex(mods: SchemaModule[]): string {
  const entities = mods.filter((m) => m.entity);
  const lines = [
    '// GENERATED by engine/schema/export.ts. Do not edit by hand: run `bun run schema:export`.',
    '// `bun run schema:export --check` fails when this file is out of date.',
    "import type { ZodType } from 'zod';",
    ...mods.map((m) => `export * from './${m.name}.ts';`),
    ...entities.map((m) => `import { ${camel(m.name)}Schema } from './${m.name}.ts';`),
    '',
    '/** Every entity schema, keyed by entity name (= the json/<name>.schema.json file name). */',
    'export const schemas: Record<string, ZodType> = {',
    ...entities.map((m) => `  '${m.name}': ${camel(m.name)}Schema,`),
    '};',
    '',
    'export const ENTITY_NAMES = [',
    ...entities.map((m) => `  '${m.name}',`),
    '] as const;',
    'export type EntityName = (typeof ENTITY_NAMES)[number];',
    '',
    '/** Library modules exported as JSON Schema `$defs` only (no entity, no registry entry). */',
    `export const LIBRARY_NAMES = [${mods.filter((m) => m.defs).map((m) => `'${m.name}'`).join(', ')}] as const;`,
    '',
  ];
  return lines.join('\n');
}

/** Every generated file, keyed by path relative to engine/schema/. */
export function generate(mods: SchemaModule[]): Map<string, string> {
  const out = new Map<string, string>();
  out.set('index.ts', renderIndex(mods));
  for (const m of mods) out.set(`json/${m.name}.schema.json`, renderJson(jsonSchemaFor(m)));
  return out;
}

/** Reads the generated files that are currently on disk (index.ts + every json/*.schema.json). */
export function readOnDisk(dir: string = SCHEMA_DIR): Map<string, string> {
  const out = new Map<string, string>();
  const idx = path.join(dir, 'index.ts');
  if (fs.existsSync(idx)) out.set('index.ts', fs.readFileSync(idx, 'utf8'));
  const jsonDir = path.join(dir, 'json');
  if (fs.existsSync(jsonDir)) {
    for (const f of fs.readdirSync(jsonDir).sort()) {
      if (f.endsWith('.schema.json')) out.set(`json/${f}`, fs.readFileSync(path.join(jsonDir, f), 'utf8'));
    }
  }
  return out;
}

/** One line per differing file; empty when `actual` equals `expected`. */
export function diffSummary(expected: Map<string, string>, actual: Map<string, string>): string[] {
  const problems: string[] = [];
  for (const [file, want] of expected) {
    const got = actual.get(file);
    if (got === undefined) {
      problems.push(`${file}: missing`);
      continue;
    }
    if (got === want) continue;
    const a = want.split('\n');
    const b = got.split('\n');
    let i = 0;
    while (i < Math.max(a.length, b.length) && a[i] === b[i]) i++;
    problems.push(`${file}: differs at line ${i + 1}: expected ${JSON.stringify(a[i] ?? '<EOF>')}, found ${JSON.stringify(b[i] ?? '<EOF>')}`);
  }
  for (const file of actual.keys()) if (!expected.has(file)) problems.push(`${file}: stale (no schema module generates it)`);
  return problems;
}

export async function check(dir: string = SCHEMA_DIR): Promise<string[]> {
  return diffSummary(generate(await loadModules(dir)), readOnDisk(dir));
}

export async function write(dir: string = SCHEMA_DIR): Promise<string[]> {
  const files = generate(await loadModules(dir));
  fs.mkdirSync(path.join(dir, 'json'), { recursive: true });
  for (const [file, content] of files) fs.writeFileSync(path.join(dir, file), content);
  const removed: string[] = [];
  for (const file of readOnDisk(dir).keys()) {
    if (!files.has(file)) {
      fs.rmSync(path.join(dir, file));
      removed.push(file);
    }
  }
  return removed;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const unknown = args.filter((a) => a !== '--check');
  if (unknown.length) {
    console.error(`unknown argument(s): ${unknown.join(' ')}\nusage: bun run schema:export [--check]`);
    process.exit(2);
  }
  if (args.includes('--check')) {
    const problems = await check();
    if (problems.length) {
      console.error(`schema:export --check: ${problems.length} generated file(s) out of date. Run \`bun run schema:export\`.`);
      for (const p of problems) console.error(`  ${p}`);
      process.exit(1);
    }
    console.log('schema:export --check: generated files are up to date');
  } else {
    const removed = await write();
    console.log(`schema:export: wrote index.ts and ${moduleNames().length} JSON Schema files${removed.length ? `, removed ${removed.join(', ')}` : ''}`);
  }
}
